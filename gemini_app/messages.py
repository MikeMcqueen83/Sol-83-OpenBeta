class Msg(str):
    """Polish text that also knows its English version."""

    def __new__(cls, key: str, **params):
        message = super().__new__(cls, CATALOG[key][0].format(**params))
        message.key = key
        message.params = params
        return message

    def en(self) -> str:
        params = {name: value.en() if isinstance(value, Msg) else value
                  for name, value in self.params.items()}
        return CATALOG[self.key][1].format(**params)


def en(value):
    """English version of a value, when it has one."""
    return value.en() if isinstance(value, Msg) else None


def in_language(message, lang: str) -> str:
    return message.en() if lang == 'en' and isinstance(message, Msg) else str(message)
